export function formatMessage(lang, key, params = {}) {
  const dict = MESSAGES[lang] || MESSAGES.zh;
  const fallback = MESSAGES.zh[key] ?? key;
  let template = dict[key] ?? fallback;
  for (const [k, v] of Object.entries(params)) {
    template = template.replaceAll(`{${k}}`, String(v));
  }
  return template;
}
